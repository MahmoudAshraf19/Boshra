    final fileName = file.uri.pathSegments.last;
    final langCode = fileName.replaceAll('app_', '').replaceAll('.arb', '');
    
    if (translations.containsKey(langCode)) {
      final content = file.readAsStringSync();
      final Map<String, dynamic> json = jsonDecode(content);
      
      bool updated = false;
      translations[langCode]!.forEach((key, value) {
        // If the key is there but equals the English value, or if it is completely missing.
        // We will just override it for these specific keys since we know they are currently English fallbacks.
        json[key] = value;
        updated = true;
      });
      
      if (updated) {
        final encoder = JsonEncoder.withIndent('  ');
        file.writeAsStringSync(encoder.convert(json));
        print('Updated $langCode');
      }
    }
  }
